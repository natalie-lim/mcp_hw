"""
retriever.py - PROVIDED. The two local lookup tools your MCP server exposes.

You do not edit this file in HW3. It contains working versions of the two
corpus tools from HW2:

    keyword_search(query) -> str        # exact-word lookup over data/corpus/
    retrieve(query, k=4) -> list[str]   # top-k chunks by embedding similarity

Both are plain Python functions. They know nothing about MCP. In Part 2 your
`mcp_server.py` imports them and wraps each one as an MCP tool. Keeping the
logic here and the MCP wrapper there means you can test either function on
its own:

    uv run python retriever.py
"""
from __future__ import annotations
import json
import re
from pathlib import Path

from embeddings import embed, cosine

CORPUS = Path(__file__).parent / "data" / "corpus"
INDEX = Path(__file__).parent / "index.json"

# Very common words carry no information about which document is relevant, so
# keyword_search ignores them when it counts matching words.
_STOPWORDS = {
    "a", "an", "and", "are", "at", "by", "did", "do", "does", "for", "how",
    "in", "is", "it", "of", "on", "or", "the", "to", "was", "what", "when",
    "where", "which", "who", "why", "with",
}


def _words(text: str) -> set[str]:
    """_words - lowercase a string and return its distinct words.

    Parameters:
        text (str): Any text, such as a query or a document.

    Returns:
        set[str]: Lowercased words with surrounding punctuation removed.
        Internal hyphens and commas in numbers are kept, so "HW3", "1,121"
        and "co-op" each stay one word.
    """
    return set(re.findall(r"[a-z0-9]+(?:[-,][a-z0-9]+)*", text.lower()))


def keyword_search(query: str, max_results: int = 2) -> str:
    """keyword_search - find the corpus passages that share the most words
    with the query.

    Parameters:
        query (str): Words to look for, such as a name, number, or course code.
        max_results (int): The most passages to return.

    Returns:
        str: Each matching passage on its own block, prefixed with its source
        filename, e.g. "[course.txt] CIS 1990 grading is ...". If no passage
        shares a word with the query, a short "no match" message.

    Description:
        Every paragraph of every corpus file gets one point for each distinct
        query word it contains. This is fast and exact, which makes it good
        for names and identifiers, but it cannot match synonyms or paraphrases.
        That gap is what ``retrieve`` covers.
    """
    query_words = _words(query) - _STOPWORDS
    scored = []
    for path in sorted(CORPUS.glob("*.txt")):
        for paragraph in path.read_text(encoding="utf-8").split("\n\n"):
            score = len(query_words & _words(paragraph))
            if score > 0:
                # Join the file's hard-wrapped lines into one line of text.
                scored.append((score, path.name, " ".join(paragraph.split())))
    if not scored:
        return f"No keyword match for '{query}' in the local corpus."
    # Highest score first. Python's sort is stable, so ties keep file order.
    scored.sort(key=lambda item: item[0], reverse=True)
    return "\n\n".join(f"[{source}] {text}"
                       for _, source, text in scored[:max_results])


def _load_index() -> list[dict]:
    """_load_index - read index.json, building it first if it is missing.

    Returns:
        list[dict]: Index entries with "text", "source", and "vector" keys.
    """
    if not INDEX.exists():
        # Imported here, not at the top, so importing retriever.py does not
        # require ingest.py unless the index actually has to be built.
        from ingest import build_index
        build_index()
    return json.loads(INDEX.read_text())


def retrieve(query: str, k: int = 4) -> list[str]:
    """retrieve - return the k chunks most similar in meaning to the query.

    Parameters:
        query (str): A natural-language question or description.
        k (int): The number of chunks to return.

    Returns:
        list[str]: Up to ``k`` chunk texts, most similar first.

    Description:
        The query is embedded with the same model used for the chunks, then
        every chunk is scored by cosine similarity. Because embeddings capture
        meaning, a query can match a chunk that uses completely different
        words (for example "how do agents use tools" vs. "ReAct pattern").
    """
    index = _load_index()
    query_vector = embed([query])[0]
    ranked = sorted(index, key=lambda entry: cosine(query_vector, entry["vector"]),
                    reverse=True)
    return [entry["text"] for entry in ranked[:k]]


