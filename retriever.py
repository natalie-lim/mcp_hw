    print("keyword_search('Comcast Technology Center') ->")
    print(keyword_search("Comcast Technology Center"))
    print("\nretrieve('how does an agent decide when to act?', k=2) ->")
    for text in retrieve("how does an agent decide when to act?", k=2):
        print("-", text[:90], "...")
