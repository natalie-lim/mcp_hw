"""Provided embeddings helper (the same file you used in HW2).

This file is provided for the assignment and is intentionally small enough to
read closely. The key points are:

1. It wraps the Gemini embedding API.
2. It caches vectors on disk so rerunning the same text does not burn quota.
3. It exposes `embed` for a batch of texts and `cosine` for comparing two
   vectors.

You do not edit this file in HW3. `ingest.py` uses it to build the vector
index, and `retriever.py` uses it to embed each `retrieve` query. The
embedding model, cache behavior, and similarity measure are part of the
shared setup used by the whole homework.
"""
from __future__ import annotations
import hashlib
import json
import math
import os
import warnings
from pathlib import Path
from dotenv import load_dotenv

warnings.filterwarnings("ignore")
from google import genai
from google.genai import types

load_dotenv(Path(__file__).parent / ".env")

CACHE_DIR = Path(__file__).parent / ".ecache"
EMBED_MODEL = "gemini-embedding-001"
_client = None


def _get_client():
    """Create and cache one Gemini client for embedding requests.

    The assignment expects the same API key setup that was used in HW1. This
    helper keeps the client in a module-level variable so later calls do not
    need to reinitialize it.
    """
    global _client
    if _client is None:
        key = os.environ.get("GEMINI_API_KEY")
        if not key:
            raise RuntimeError("Set GEMINI_API_KEY (copy .env.example to .env).")
        _client = genai.Client(api_key=key)
    return _client


def embed(texts: list[str]) -> list[list[float]]:
    """Return one embedding vector for each input text.

    The function caches each text by hashing the raw string. If the text has
    already been embedded, it loads the saved vector from disk instead of making
    another API call. This keeps the index build and retrieval system efficient
    and avoids re-embedding the same chunk repeatedly.
    """
    CACHE_DIR.mkdir(exist_ok=True)
    out: list[list[float] | None] = []
    missing, missing_idx = [], []
    for i, t in enumerate(texts):
        f = CACHE_DIR / f"{hashlib.sha256(t.encode()).hexdigest()}.json"
        if f.exists():
            out.append(json.loads(f.read_text()))
        else:
            out.append(None)
            missing.append(t)
            missing_idx.append(i)
    if missing:
        resp = _get_client().models.embed_content(
            model=EMBED_MODEL,
            contents=missing,
            config=types.EmbedContentConfig(task_type="SEMANTIC_SIMILARITY"),
        )
        for j, e in zip(missing_idx, resp.embeddings):
            vec = list(e.values)
            out[j] = vec
            f = CACHE_DIR / f"{hashlib.sha256(texts[j].encode()).hexdigest()}.json"
            f.write_text(json.dumps(vec))
    return out  # type: ignore[return-value]


def cosine(a: list[float], b: list[float]) -> float:
    """Compute cosine similarity between two vectors.

    Cosine similarity measures the angle between vectors instead of their raw
    magnitude. It is the standard choice for embedding-based retrieval because it
    gives a value between -1 and 1, and it rewards vectors that point in the
    same direction even when their lengths differ.
    """
    dot = sum(x * y for x, y in zip(a, b))
    na = math.sqrt(sum(x * x for x in a))
    nb = math.sqrt(sum(y * y for y in b))
    return dot / (na * nb) if na and nb else 0.0


if __name__ == "__main__":
    words = ["king", "queen", "banana", "monarch"]
    v = embed(words)
    for i in range(len(words)):
        for j in range(i + 1, len(words)):
            print(f"{words[i]:8s} ~ {words[j]:8s} = {cosine(v[i], v[j]):+.3f}")
