"""
ingest.py - PROVIDED. Build the vector index used by `retrieve`.

You do not edit this file in HW3. It is a complete, working version of the
index builder you wrote in HW2, so everyone starts HW3 from the same
retrieval code.

It loads every file in data/corpus/, splits each one into overlapping word
chunks, embeds each chunk with `embeddings.embed`, and writes index.json:

    [{"text": "...", "source": "course.txt", "vector": [0.01, ...]}, ...]

Run it once after setup (and again if you change anything in data/corpus/):

    uv run python ingest.py

Embeddings are cached in .ecache/, so rerunning only embeds new or changed
chunks and does not spend extra API quota.
"""
from __future__ import annotations
import json
from pathlib import Path

from embeddings import embed

CORPUS = Path(__file__).parent / "data" / "corpus"
INDEX = Path(__file__).parent / "index.json"

# The HW3 corpus is a handful of short documents (25-85 words each), so a
# 60-word chunk holds roughly one paragraph. The 15-word overlap keeps a fact
# that falls on a chunk boundary readable in at least one chunk.
CHUNK_WORDS = 60
OVERLAP = 15


def chunk(text: str, size: int = CHUNK_WORDS, overlap: int = OVERLAP) -> list[str]:
    """chunk - split text into overlapping word windows.

    Parameters:
        text (str): The full document text.
        size (int): The number of words in each chunk.
        overlap (int): The number of words shared by neighboring chunks.

    Returns:
        list[str]: The chunks in document order. A document no longer than
        ``size`` words becomes a single chunk.

    Description:
        The window moves forward by ``size - overlap`` words each step, so
        neighboring chunks share ``overlap`` words and no word is dropped.
    """
    if size <= 0 or overlap < 0 or overlap >= size:
        raise ValueError("need size > 0 and 0 <= overlap < size")
    words = text.split()
    if len(words) <= size:
        return [" ".join(words)] if words else []
    chunks = []
    step = size - overlap
    for start in range(0, len(words), step):
        chunks.append(" ".join(words[start:start + size]))
        # Stop once this window reached the last word, so the final chunk is
        # not followed by a tiny chunk that only repeats the overlap.
        if start + size >= len(words):
            break
    return chunks


def build_index() -> list[dict]:
    """build_index - chunk, embed, and save every corpus document.

    Returns:
        list[dict]: The index entries that were written to ``index.json``.

    Description:
        Files are read in sorted order so the index is identical on every
        run. All chunk texts are embedded in one ``embed`` call, which is
        faster than one call per chunk and uses the on-disk cache.
    """
    records = []
    for path in sorted(CORPUS.glob("*.txt")):
        for piece in chunk(path.read_text(encoding="utf-8")):
            records.append({"text": piece, "source": path.name})
    vectors = embed([record["text"] for record in records])
    for record, vector in zip(records, vectors):
        record["vector"] = vector
    INDEX.write_text(json.dumps(records))
    return records


if __name__ == "__main__":
    records = build_index()
    print(f"indexed {len(records)} chunks -> {INDEX.name}")
